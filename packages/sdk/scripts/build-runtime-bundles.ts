// Builds separate client and local Source bundles for CLI Workers.
// Runs as part of the SDK build and writes only to this package's dist directory.
import { existsSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const sdk = join(here, "..")
const distEntry = join(sdk, "dist", "runtime.js")
if (!existsSync(distEntry)) {
  throw new Error(`Missing SDK dist: ${distEntry}. Run tsdown first.`)
}
const built = await Bun.build({ entrypoints: [distEntry], format: "esm", target: "node" })
if (!built.success) {
  throw new Error(`SDK bundle failed: ${built.logs.join("\n")}`)
}
const bundled = (await built.outputs[0]!.text())
  // Bun annotates bundled chunks with cwd-relative source paths, which differ
  // by invocation directory. Normalize them so the vendored file is stable.
  .split("\n")
  .map(line => /^\s*\/\/\s*\S*dist\/\S+\.js\s*$/.test(line) ? "// <sdk-chunk>" : line)
  .join("\n")
const header = [
  "// Generated bundle of @newsnext/sdk/runtime for CLI Workers. Do not edit.",
  "// Regenerated by `bun --filter=@newsnext/sdk run build`.",
  "",
].join("\n")
const target = join(sdk, "dist", "newsnext-sdk.mjs")
writeFileSync(target, header + bundled)
console.log(`Built portable SDK bundle at ${target}`)

// Build from the restricted module-host entry, never the full Source engine.
const sourceBuilt = await Bun.build({
  entrypoints: [join(sdk, "src", "source", "local", "runtime.ts")],
  format: "esm",
  target: "node",
  minify: true,
})
if (!sourceBuilt.success) {
  throw new Error(`Source bundle failed: ${sourceBuilt.logs.join("\n")}`)
}
// Minification emits raw tabs inside encoding-table strings.
const sourceCode = (await sourceBuilt.outputs[0]!.text()).replaceAll("\t", "\\t")
const sourceTarget = join(sdk, "dist", "newsnext-source-runtime.mjs")
writeFileSync(sourceTarget, [
  "// Generated bundle of the SDK local Source runtime. Do not edit.",
  "// Regenerated by `bun --filter=@newsnext/sdk run build`.",
  sourceCode,
].join("\n"))
console.log(`Built portable Source bundle at ${sourceTarget}`)
