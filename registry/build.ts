import { basename, dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { resolveProvider } from "@newsnext/sdk/source/registry"

const rootDir = dirname(fileURLToPath(import.meta.url))
const providerGlobs = ["src/*.json", "src/*.js", "src/**/index.js"]
const TEST_FILE_REGEX = /\.(?:test|spec)\.js$/
const check = Bun.argv.includes("--check")

async function writeIfChanged(path: string, content: string): Promise<void> {
  const file = Bun.file(path)
  const currentContent = await file.exists() ? await file.text() : undefined
  if (currentContent !== content) await file.write(content)
}

async function generate(): Promise<void> {
  const files = new Set<string>()
  for (const pattern of providerGlobs) {
    for await (const path of new Bun.Glob(pattern).scan(rootDir)) {
      const file = path.replaceAll("\\", "/")
      if (!TEST_FILE_REGEX.test(file)) files.add(file)
    }
  }

  const providers = new Map<string, string>()
  let sourceCount = 0
  for (const file of Array.from(files).sort()) {
    const providerId = basename(file) === "index.js"
      ? basename(dirname(file))
      : basename(file).replace(/\.(?:json|js)$/, "")
    if (providers.has(providerId)) throw new Error(`Duplicate provider ID "${providerId}"`)

    const path = join(rootDir, file)
    try {
      const module = await import(path) as { default: unknown }
      const provider = module.default
      sourceCount += Object.keys(resolveProvider(providerId, provider).sources).length
    } catch (error) {
      throw new Error(`Invalid Source provider '${file}'`, { cause: error })
    }
    providers.set(providerId, file)
  }

  if (!check) {
    const entries = Array.from(providers)
    const imports = entries.map(([, file], index) => `import provider_${index} from "./${file}"`)
    const properties = entries.map(([id], index) => `  ${JSON.stringify(id)}: provider_${index},`)
    await writeIfChanged(join(rootDir, "sources.js"), `// Auto-generated by build.ts; do not edit manually.\n${imports.join("\n")}\n\nexport default {\n${properties.join("\n")}\n}\n`)
    await writeIfChanged(join(rootDir, "sources.d.ts"), `// Auto-generated by build.ts; do not edit manually.\nimport type { ProviderConfig } from "@newsnext/sdk/source/registry"\n\ndeclare const providers: Record<string, ProviderConfig>\nexport default providers\n`)
  }
  console.log(`Validated ${providers.size} Providers and ${sourceCount} Sources${check ? "" : "; generated Provider imports"}`)
}

await generate()
